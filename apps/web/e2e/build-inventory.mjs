// Aggregate the Survey Crawler results (e2e/results/*.json) into the human-readable,
// triaged demo-readiness/inventory.md. Run: `node e2e/build-inventory.mjs` (from apps/web).
//
// Sprint 0 of the Demo-Readiness Program. Reads one JSON file per (role × module) written
// by survey.spec.ts, emits the summary counts, the full detail table, and the EMPTY/ERROR
// backlog grouped by the Sprint 1–6 module clusters.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url)); // apps/web/e2e
const REPO_ROOT = path.resolve(HERE, '../../..'); // HRMS
const RESULTS_DIR = path.join(HERE, 'results');
const OUT = path.join(REPO_ROOT, 'demo-readiness', 'inventory.md');

// Plan order (also the canonical module list) + which sprint cluster each belongs to.
const MODULE_ORDER = [
  'cold-start-setup', 'core-hr', 'leave-management',
  'attendance', 'daily-work-logging', 'payroll-processing',
  'talent-acquisition', 'onboarding-offboarding', 'performance-growth',
  'learning-development', 'compensation-rewards', 'expense-management',
  'engagement-culture', 'compliance-audit', 'workforce-planning',
  'integrations-api', 'people-analytics', 'platform-experience', 'demo-company',
];
const SPRINT_OF = {
  'cold-start-setup': 1, 'core-hr': 1, 'leave-management': 1,
  'attendance': 2, 'daily-work-logging': 2, 'payroll-processing': 2,
  'talent-acquisition': 3, 'onboarding-offboarding': 3, 'performance-growth': 3,
  'learning-development': 4, 'compensation-rewards': 4, 'expense-management': 4,
  'engagement-culture': 5, 'compliance-audit': 5, 'workforce-planning': 5,
  'integrations-api': 6, 'people-analytics': 6, 'platform-experience': 6, 'demo-company': 6,
};
const ROLE_ORDER = ['admin', 'manager', 'employee'];

function loadRows() {
  if (!fs.existsSync(RESULTS_DIR)) {
    console.error(`[report] No results dir at ${RESULTS_DIR}. Run the survey first: pnpm test:survey`);
    process.exit(1);
  }
  const files = fs.readdirSync(RESULTS_DIR).filter((f) => f.endsWith('.json'));
  const rows = [];
  for (const f of files) {
    try {
      const arr = JSON.parse(fs.readFileSync(path.join(RESULTS_DIR, f), 'utf8'));
      if (Array.isArray(arr)) rows.push(...arr);
    } catch (e) {
      console.error(`[report] Skipping unreadable ${f}: ${e}`);
    }
  }
  return rows;
}

function sortKey(r) {
  const m = MODULE_ORDER.indexOf(r.mod);
  const ro = ROLE_ORDER.indexOf(r.role);
  return [m < 0 ? 99 : m, ro < 0 ? 99 : ro, r.tabIndex ?? 0];
}
function bySort(a, b) {
  const ka = sortKey(a), kb = sortKey(b);
  for (let i = 0; i < ka.length; i++) if (ka[i] !== kb[i]) return ka[i] - kb[i];
  return 0;
}

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').trim();
function shotLink(rel) {
  if (!rel) return '—';
  return `[png](../apps/web/${rel})`;
}
const BADGE = { OK: 'OK', EMPTY: '⚠️ EMPTY', ERROR: '🔴 ERROR', GUARDED: '🛡️ GUARDED' };

function build() {
  const rows = loadRows().sort(bySort);
  const total = rows.length;

  // ── Summary counts ──
  const perRole = {};
  for (const role of ROLE_ORDER) perRole[role] = { OK: 0, EMPTY: 0, ERROR: 0, GUARDED: 0, total: 0 };
  const all = { OK: 0, EMPTY: 0, ERROR: 0, GUARDED: 0, total: 0 };
  for (const r of rows) {
    const bucket = perRole[r.role] || (perRole[r.role] = { OK: 0, EMPTY: 0, ERROR: 0, GUARDED: 0, total: 0 });
    bucket[r.status] = (bucket[r.status] || 0) + 1;
    bucket.total++;
    all[r.status] = (all[r.status] || 0) + 1;
    all.total++;
  }

  // ── Coverage / anomalies ──
  const seen = new Set(rows.map((r) => `${r.mod}__${r.role}`));
  const missing = [];
  for (const mod of MODULE_ORDER) {
    for (const role of ROLE_ORDER) {
      if (!seen.has(`${mod}__${role}`)) missing.push(`${mod} / ${role}`);
    }
  }
  const zeroTab = []; // module×role that produced a single 'default' row (no tabs discovered)
  const grouped = {};
  for (const r of rows) {
    const k = `${r.mod}__${r.role}`;
    (grouped[k] ||= []).push(r);
  }
  for (const [k, rs] of Object.entries(grouped)) {
    if (rs.length === 1 && rs[0].status === 'GUARDED') continue; // expected: role-guarded cell
    if (rs.length === 1 && (rs[0].tab === 'default' || rs[0].note)) {
      zeroTab.push(`${k.replace('__', ' / ')} — ${rs[0].note || 'single default view, no tab bar'}`);
    }
  }

  const today = new Date().toISOString().slice(0, 10);

  let md = '';
  md += `# Demo-Readiness Inventory (living)\n\n`;
  md += `> Generated by the Survey Crawler (\`apps/web/e2e/survey.spec.ts\`) and updated after **every** sprint.\n`;
  md += `> Status legend: **OK** = renders with real data, no errors · **⚠️ EMPTY** = renders but blank/zero where it should have data · **🔴 ERROR** = console/page error, failed \`/api/v1/*\` call, or error boundary · **🛡️ GUARDED** = module intentionally hidden for this role; the deep link redirected to /dashboard (counts as OK).\n`;
  md += `> The green gate: this table is **100% OK or GUARDED** across all rows.\n\n`;
  md += `_Last survey run: ${today} · ${total} tab-views across ${Object.keys(grouped).length} module×role views._\n\n`;

  md += `## How this gets filled\n`;
  md += `1. App up (\`pnpm dev\`) + data (\`pnpm seed\`). 2. \`pnpm --filter @hrms/web test:survey\` (writes \`apps/web/e2e/results/*.json\` + screenshots). 3. \`pnpm --filter @hrms/web survey:report\` regenerates this file.\n\n`;

  // ── Summary ──
  md += `## Summary\n`;
  md += `| | OK | EMPTY | ERROR | GUARDED | Total |\n|---|---|---|---|---|---|\n`;
  for (const role of ROLE_ORDER) {
    const b = perRole[role];
    md += `| ${role} | ${b.OK} | ${b.EMPTY} | ${b.ERROR} | ${b.GUARDED} | ${b.total} |\n`;
  }
  md += `| **All** | **${all.OK}** | **${all.EMPTY}** | **${all.ERROR}** | **${all.GUARDED}** | **${all.total}** |\n\n`;

  if (missing.length) {
    md += `> ⚠️ **Missing coverage (${missing.length}):** ${missing.join(', ')} — no result file. (Survey error or skipped.)\n\n`;
  }
  if (zeroTab.length) {
    md += `<details><summary>⚠️ Module×role views with no tab bar / special screen (${zeroTab.length})</summary>\n\n`;
    for (const z of zeroTab) md += `- ${z}\n`;
    md += `\n</details>\n\n`;
  }

  // ── Triaged backlog (EMPTY/ERROR only), grouped by sprint cluster ──
  const todo = rows.filter((r) => r.status !== 'OK' && r.status !== 'GUARDED');
  md += `## Triaged backlog — EMPTY / ERROR by sprint cluster (${todo.length} of ${total})\n\n`;
  for (let s = 1; s <= 6; s++) {
    const mods = MODULE_ORDER.filter((m) => SPRINT_OF[m] === s);
    const items = todo.filter((r) => SPRINT_OF[r.mod] === s).sort(bySort);
    const e = items.filter((r) => r.status === 'ERROR').length;
    const m = items.filter((r) => r.status === 'EMPTY').length;
    md += `### Sprint ${s} — ${mods.join(', ')}  · ${items.length} to fix (🔴 ${e} / ⚠️ ${m})\n`;
    if (!items.length) {
      md += `_All green._\n\n`;
      continue;
    }
    md += `| Module | Role | Tab | Status | Notes |\n|---|---|---|---|---|\n`;
    for (const r of items) {
      md += `| ${esc(r.mod)} | ${esc(r.role)} | ${esc(r.tab)} | ${BADGE[r.status]} | ${esc(r.note) || '—'} |\n`;
    }
    md += `\n`;
  }

  // ── Full detail ──
  md += `## Detail (all ${total} tab-views)\n\n`;
  md += `| Module | Role | Tab | Status | Notes | Screenshot |\n|---|---|---|---|---|---|\n`;
  for (const r of rows) {
    md += `| ${esc(r.mod)} | ${esc(r.role)} | ${esc(r.tab)} | ${BADGE[r.status]} | ${esc(r.note) || '—'} | ${shotLink(r.screenshot)} |\n`;
  }
  md += `\n`;

  fs.writeFileSync(OUT, md);
  console.log(`[report] Wrote ${OUT}`);
  console.log(`[report] ${total} tab-views — OK:${all.OK}  EMPTY:${all.EMPTY}  ERROR:${all.ERROR}  GUARDED:${all.GUARDED}`);
  for (const role of ROLE_ORDER) {
    const b = perRole[role];
    console.log(`[report]   ${role.padEnd(9)} OK:${b.OK}  EMPTY:${b.EMPTY}  ERROR:${b.ERROR}  GUARDED:${b.GUARDED}  (${b.total})`);
  }
  if (missing.length) console.log(`[report] MISSING coverage: ${missing.length} module×role views`);
}

build();
